/** Fırın gerektiren tarifler: adımlardan sıcaklık bulunur ve önceden ısıtma notu eklenir. */
export function firinNotu(t) {
  const m = t.adim.join(' ').match(/(\d{3})\s*°C/);
  return m ? `Fırını ${m[1]} °C'ye ısıtmaya başlayın.` : null;
}
